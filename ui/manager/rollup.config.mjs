/**
 * rollup configuration file that reproduce `react-scripts build`
 *
 * Builds one self-contained SPA per manager section (configuration,
 * sessions, ...). Each entry produces its own HTML page + hashed bundle and
 * shares the common source tree (Navbar, theme, tree, ...).
 *
 * @copyright Yadd <yadd@debian.org>
 * license MIT
 */
import babel from "@rollup/plugin-babel";
import commonjs from "@rollup/plugin-commonjs";
import html from "@rollup/plugin-html";
import image from "@rollup/plugin-image";
import inject from "@rollup/plugin-inject";
import json from "@rollup/plugin-json";
import { nodeResolve } from "@rollup/plugin-node-resolve";
import replace from "@rollup/plugin-replace";
import svgr from "@svgr/rollup";
import postcssModules from "postcss-modules";
import postcssPresetEnv from "postcss-preset-env";
import postcss from "rollup-plugin-postcss";
import typescript from "@rollup/plugin-typescript";
import progress from "rollup-plugin-progress";
import { createHash } from "node:crypto";

// https://github.com/d3/d3-interpolate/issues/58
const D3_WARNING = /Circular dependency.*d3-interpolate/;

// The generated page is an HTML::Template served by the manager, not a static
// file: asset URLs go through STATIC_PREFIX (the static directory is a
// deployment setting). Bundle names are stable, so cache-busting relies on a
// per-file content hash baked in the ?v query at build time: it changes on
// every content change, unlike the version-based CACHE_TAG which would serve
// a stale bundle between two builds of the same release.
const htmlTemplate =
  (title) =>
  ({ attributes, files, publicPath, bundle }) => {
    // "static/new/foo.ext" is served from STATIC_PREFIX, which ends with /
    const url = (b) => {
      // Hash the readable bundle content: it changes on every code change, so
      // it also busts the cache of the matching .min file built afterwards.
      const hash = createHash("sha256")
        .update(b.code ?? b.source ?? "")
        .digest("hex")
        .slice(0, 12);
      // The page loads the minified asset (produced by `make minify`); rollup
      // only emits the readable source next to it.
      const name = b.fileName
        .replace(/^static\//, "")
        .replace(/\.(js|css)$/, ".min.$1");
      return `<TMPL_VAR NAME="STATIC_PREFIX">${name}?v=${hash}`;
    };
    // psgi.js is generated by the manager and defines the globals the app
    // needs (scriptname, links, menulinks, ...). It is loaded as a regular
    // same-origin script, so that it is covered by 'self' in the CSP: its
    // content is dynamic, so no hash could ever cover an inline injection
    let scripts = `<script src="<TMPL_VAR NAME="SCRIPTNAME">psgi.js"></script>`;
    (files.js || []).forEach((b) => {
      scripts += `\n    <script src="${url(b)}"></script>`;
    });
    // CSS is extracted to a real file so that it is covered by "self" in the
    // Content-Security-Policy, instead of being injected as an inline <style>
    let styles = "";
    (files.css || []).forEach((b) => {
      styles += `\n    <link rel="stylesheet" href="${url(b)}" />`;
    });
    const makeAttrs = (attrs = {}) =>
      Object.entries(attrs)
        .map(([key, value]) => `${key}="${value}"`)
        .join(" ");
    return `<!DOCTYPE html>
<html ${makeAttrs(attributes.html)}>
  <head>
    <title>${title}</title>
    <link rel="icon" href="<TMPL_VAR NAME="STATIC_PREFIX">logos/favicon.ico" />${styles}
  </head>
  <body>
    <div id="root" />
    ${scripts}
  </body>
</html>`;
  };

// Build one SPA configuration.
//  - input:  entry file
//  - route:  manager route serving the page, injected as REACT_APP_HTMLNAME.
//            It must match the plugin defaultRoute, so that the navbar can
//            highlight the active section.
//  - tpl:    HTML::Template produced, relative to the manager template dir
//  - prefix: bundle name (static/new/<prefix>.js). Names are stable: cache
//            invalidation relies on the CACHE_TAG query parameter.
//  - title:  HTML <title>
const makeConfig = ({ input, route, tpl, prefix, title }) => ({
  input: [input],
  output: {
    dir: "dist",
    format: "iife",
    // "hidden" still emits the .map for local debugging but omits the
    // //# sourceMappingURL comment: the maps are not deployed to the static
    // dir, so a plain "true" would make every browser request a 404 map.
    sourcemap: "hidden",
    entryFileNames: `static/new/${prefix}.js`,
    inlineDynamicImports: true,
  },
  onwarn(warning, warn) {
    if (D3_WARNING.test(warning)) return;
    if (warning.code === "THIS_IS_UNDEFINED") return;
    if (warning.code === "MODULE_LEVEL_DIRECTIVE") return;
    warn(warning);
  },
  plugins: [
    progress(),
    svgr(),
    image(),
    nodeResolve({
      browser: true,
      extensions: [".js", ".ts", ".jsx", ".tsx"],
    }),
    babel({
      presets: ["@babel/env", "@babel/preset-react"],
      plugins: ["@babel/plugin-transform-react-jsx"],
      babelHelpers: "bundled",
    }),
    json(),
    replace({
      "process.env.NODE_ENV":
        process.env.NODE_ENV === "development"
          ? JSON.stringify("development")
          : JSON.stringify("production"),
      preventAssignment: true,
      "process.env.REACT_APP_HTMLNAME": `"${route}"`,
    }),
    typescript({
      tsconfig: "./tsconfig.build.json",
      declaration: false,
      // Type errors are only warnings by default: abort the build instead
      noEmitOnError: true,
    }),
    postcss({
      // Produce static/new/<prefix>.css instead of injecting a <style> at
      // runtime: an inline <style> has no URL, so no CSP source can cover it.
      // The path must be given explicitly, "true" would ignore entryFileNames
      // and drop the file at the root of the output directory
      extract: `static/new/${prefix}.css`,
      plugins: [
        postcssModules({
          generateScopedName: "[local]",
        }),
        postcssPresetEnv({
          stage: 0,
        }),
      ],
    }),
    commonjs(),
    inject({
      React: "react",
    }),
    html({
      fileName: tpl,
      title,
      template: htmlTemplate(title),
    }),
    // NB: no terser here. Rollup emits a readable bundle (so a source stays
    // available to anyone who does not recompile the TypeScript); the served
    // *.min.js / *.min.css are produced by `make minify`, like every other
    // LLNG asset. The template below already points at the .min files.
  ],
});

export default [
  makeConfig({
    input: "src/index.tsx",
    route: "manager.html",
    tpl: "templates/new/manager.tpl",
    prefix: "manager",
    title: "LemonLDAP::NG Manager",
  }),
  makeConfig({
    input: "src/sessions.tsx",
    route: "sessions.html",
    tpl: "templates/new/sessions.tpl",
    prefix: "sessions",
    title: "LemonLDAP::NG Sessions",
  }),
  makeConfig({
    input: "src/notifications.tsx",
    route: "notifications.html",
    tpl: "templates/new/notifications.tpl",
    prefix: "notifications",
    title: "LemonLDAP::NG Notifications",
  }),
  makeConfig({
    input: "src/twofa.tsx",
    route: "2ndfa.html",
    tpl: "templates/new/2ndfa.tpl",
    prefix: "twofa",
    title: "LemonLDAP::NG Second Factors",
  }),
];
